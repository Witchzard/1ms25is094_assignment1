import { PaperAnalysis } from '../types.ts';

export function generateTextReport(analysis: PaperAnalysis, originalText?: string): string {
  const divider = '================================================================================';
  const subDivider = '--------------------------------------------------------------------------------';

  let report = `${divider}\n`;
  report += `RESEARCH PAPER COMPREHENSIVE ANALYSIS REPORT\n`;
  report += `Generated by Research Paper AI Agent\n`;
  report += `Date: ${new Date(analysis.analyzedAt).toLocaleString()}\n`;
  report += `${divider}\n\n`;

  report += `1. PAPER METADATA\n`;
  report += `${subDivider}\n`;
  report += `Title: ${analysis.title}\n`;
  if (analysis.keyExtraction.authors) {
    report += `Authors: ${analysis.keyExtraction.authors}\n`;
  }
  report += `Word Count: ${analysis.wordCount} words\n`;
  report += `Estimated Reading Time: ~${analysis.readingTimeMinutes} minutes\n\n`;

  report += `2. STRUCTURED CORE SUMMARY (Few-Shot Guided)\n`;
  report += `${subDivider}\n`;
  if (analysis.structuredSummary) {
    report += `- Objective: ${analysis.structuredSummary.objective}\n`;
    report += `- Methodology: ${analysis.structuredSummary.methodology}\n`;
    report += `- Findings: ${analysis.structuredSummary.findings}\n`;
    report += `- Research gap: ${analysis.structuredSummary.researchGap}\n\n`;
  } else {
    report += `- Objective: ${analysis.summary.objective}\n`;
    report += `- Methodology: ${analysis.summary.methodology}\n`;
    report += `- Findings: ${analysis.summary.findings}\n`;
    report += `- Research gap: ${analysis.researchGaps.statedLimitations[0] || 'Information not available'}\n\n`;
  }

  report += `3. DETAILED ACADEMIC BREAKDOWN & SYNTHESIS\n`;
  report += `${subDivider}\n`;
  report += `EXECUTIVE SUMMARY:\n${analysis.summary.executiveSummary}\n\n`;
  report += `MAIN OBJECTIVE:\n${analysis.summary.objective}\n\n`;
  report += `METHODOLOGY OVERVIEW:\n${analysis.summary.methodology}\n\n`;
  report += `KEY FINDINGS:\n${analysis.summary.findings}\n\n`;
  report += `CONCLUSION:\n${analysis.summary.conclusion}\n\n`;

  report += `3. KEY INFORMATION EXTRACTION\n`;
  report += `${subDivider}\n`;
  report += `RESEARCH PROBLEM:\n${analysis.keyExtraction.problem}\n\n`;
  report += `SPECIFIC RESEARCH OBJECTIVES:\n`;
  analysis.keyExtraction.objectives.forEach((obj, idx) => {
    report += `  ${idx + 1}. ${obj}\n`;
  });
  report += `\nMETHODOLOGY DETAILS:\n`;
  report += `  - Approach: ${analysis.keyExtraction.methodologyDetail.approach}\n`;
  report += `  - Architecture / Design: ${analysis.keyExtraction.methodologyDetail.architectureOrDesign}\n`;
  report += `  - Data Collection & Corpus: ${analysis.keyExtraction.methodologyDetail.dataCollection}\n\n`;

  report += `TECHNOLOGIES & ENVIRONMENT:\n`;
  report += `  - Frameworks & Tools: ${analysis.keyExtraction.technologies.frameworksAndTools.join(', ') || 'N/A'}\n`;
  report += `  - Models & Baselines: ${analysis.keyExtraction.technologies.modelsOrBaselines.join(', ') || 'N/A'}\n`;
  report += `  - Datasets: ${analysis.keyExtraction.technologies.datasets.join(', ') || 'N/A'}\n`;
  report += `  - Hardware / Compute: ${analysis.keyExtraction.technologies.hardwareOrEnvironments.join(', ') || 'N/A'}\n\n`;

  report += `IMPORTANT QUANTITATIVE & QUALITATIVE RESULTS:\n`;
  analysis.keyExtraction.keyResults.forEach((res, idx) => {
    report += `  [Result ${idx + 1}] ${res.metricOrFinding}\n`;
    report += `    Measured Value: ${res.valueOrEvidence}\n`;
    report += `    Significance: ${res.significance}\n\n`;
  });

  report += `4. RESEARCH GAPS & LIMITATIONS\n`;
  report += `${subDivider}\n`;
  report += `AUTHORS' STATED LIMITATIONS:\n`;
  analysis.researchGaps.statedLimitations.forEach((lim, idx) => {
    report += `  - ${lim}\n`;
  });
  report += `\nUNADDRESSED GAPS & EXTENSIONS:\n`;
  analysis.researchGaps.unaddressedGaps.forEach((gap, idx) => {
    report += `  - ${gap}\n`;
  });
  report += `\nRECOMMENDED FUTURE RESEARCH DIRECTIONS:\n`;
  analysis.researchGaps.futureDirections.forEach((dir, idx) => {
    report += `  - ${dir}\n`;
  });
  report += `\n\n`;

  report += `5. TECHNICAL KEYWORDS & PLAIN-LANGUAGE GLOSSARY\n`;
  report += `${subDivider}\n`;
  analysis.keywords.forEach((kw) => {
    report += `TERM: ${kw.term} [Category: ${kw.category}]\n`;
    report += `  Plain English Explanation: ${kw.plainExplanation}\n`;
    report += `  Academic Definition: ${kw.academicDefinition}\n\n`;
  });

  report += `${divider}\n`;
  report += `End of Report — Research Paper AI Agent\n`;
  report += `${divider}\n`;

  return report;
}

export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
